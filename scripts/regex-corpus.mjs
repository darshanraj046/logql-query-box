const ATOMS = ['a', 'b', '.', '\\d', '\\w', '\\s', '\\b', '\\x41', '\\pL', '[a-z]', '[^0-9]', '[[:alpha:]]', '(?:a)', '(a)', '(?i)', '(?P<n>a)', '^', '$', '\\.', '-', '\\Qx\\E', '[]x]', '{', '}', ']', '\\1', '(?=a)', '\\y', '[', '(', ')']
const REPEATS = ['', '', '', '*', '+', '?', '*?', '+?', '??', '{2}', '{1,3}', '{2,}', '{1001}', '**', '{,2}']

export function regexCorpus(count = 20000, seed = 20261101) {
  const r = rng(seed)
  const pick = (a) => a[Math.floor(r() * a.length)]
  const out = new Set(HAND)
  while (out.size < HAND.length + count) {
    let p = ''
    const n = 1 + Math.floor(r() * 5)
    for (let i = 0; i < n; i++) {
      p += pick(ATOMS) + pick(REPEATS)
      if (r() < 0.15) p += '|'
    }
    out.add(p)
  }
  return [...out]
}
